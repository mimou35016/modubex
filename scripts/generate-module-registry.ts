import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import * as prettier from "prettier";

const root = process.cwd();
const modulesDir = path.join(root, "src", "modules");
const outputFile = path.join(modulesDir, "registry.generated.ts");
const checkOnly = process.argv.includes("--check");

const locales = ["en", "fr", "ar"] as const;
const moduleIdPattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

type ModulePlan = {
  id: string;
  routes: readonly string[];
  cleanup: boolean;
  messages: Readonly<Record<(typeof locales)[number], boolean>>;
};

function identifier(value: string): string {
  return value.replace(/-([a-z0-9])/g, (_match, character: string) => character.toUpperCase());
}

function capital(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function scanModules(): readonly ModulePlan[] {
  if (!existsSync(modulesDir)) return [];
  const plans: ModulePlan[] = [];

  for (const entry of readdirSync(modulesDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === "registry.generated.ts") continue;
    const id = entry.name;
    if (!moduleIdPattern.test(id)) {
      throw new Error(`Invalid module directory name "${id}"; expected a lowercase module id.`);
    }
    const dir = path.join(modulesDir, id);
    if (!existsSync(path.join(dir, "manifest.ts"))) {
      throw new Error(`Module ${id} is missing manifest.ts.`);
    }

    const routesDir = path.join(dir, "routes");
    const routes = existsSync(routesDir)
      ? readdirSync(routesDir, { withFileTypes: true })
          .filter((file) => file.isFile() && file.name.endsWith(".tsx"))
          .map((file) => {
            const key = file.name.slice(0, -".tsx".length);
            if (!moduleIdPattern.test(key)) {
              throw new Error(`Invalid route file name "${file.name}" in module ${id}.`);
            }
            return key;
          })
          .sort()
      : [];

    const messages = Object.fromEntries(
      locales.map((locale) => [locale, existsSync(path.join(dir, "messages", `${locale}.json`))]),
    ) as Record<(typeof locales)[number], boolean>;

    plans.push({
      id,
      routes,
      cleanup: existsSync(path.join(dir, "cleanup.ts")),
      messages,
    });
  }

  return plans.sort((a, b) => a.id.localeCompare(b.id));
}

function render(plans: readonly ModulePlan[]): string {
  const lines: string[] = [
    "// Generated by scripts/generate-module-registry.ts. Do not edit by hand.",
    'import type { ModuleDefinition } from "@/core/modules/manifest";',
  ];

  for (const plan of plans) {
    const base = identifier(plan.id);
    lines.push(`import ${base}Manifest from "@/modules/${plan.id}/manifest";`);
    for (const route of plan.routes) {
      lines.push(
        `import ${base}${identifier(route)}Route from "@/modules/${plan.id}/routes/${route}";`,
      );
    }
    if (plan.cleanup) {
      lines.push(`import ${base}Cleanup from "@/modules/${plan.id}/cleanup";`);
    }
    for (const locale of locales) {
      if (plan.messages[locale]) {
        lines.push(
          `import ${base}${capital(locale)}Messages from "@/modules/${plan.id}/messages/${locale}.json";`,
        );
      }
    }
  }

  lines.push("");
  lines.push("export const moduleDefinitions: readonly ModuleDefinition[] = [");
  for (const plan of plans) {
    const base = identifier(plan.id);
    lines.push("  {");
    lines.push(`    manifest: ${base}Manifest,`);
    if (plan.routes.length === 0) {
      lines.push("    routes: {},");
    } else {
      lines.push("    routes: {");
      for (const route of plan.routes) {
        lines.push(`      ${JSON.stringify(route)}: ${base}${identifier(route)}Route,`);
      }
      lines.push("    },");
    }
    if (plan.cleanup) lines.push(`    cleanup: ${base}Cleanup,`);
    lines.push("    messages: {");
    for (const locale of locales) {
      const value = plan.messages[locale]
        ? `${base}${capital(locale)}Messages as Record<string, unknown>`
        : "{} as Record<string, unknown>";
      lines.push(`      ${locale}: async () => ${value},`);
    }
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("];");

  return `${lines.join("\n")}\n`;
}

async function main(): Promise<void> {
  const plans = scanModules();
  const config = await prettier.resolveConfig(outputFile);
  const content = await prettier.format(render(plans), {
    ...(config ?? {}),
    filepath: outputFile,
  });

  if (checkOnly) {
    const current = existsSync(outputFile) ? readFileSync(outputFile, "utf8") : "";
    if (current !== content) {
      console.error("Module registry is stale. Run `npm run modules:generate`.");
      process.exitCode = 1;
    } else {
      console.info(`Module registry is up to date (${plans.length} module(s)).`);
    }
    return;
  }

  mkdirSync(path.dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, content, "utf8");
  console.info(`Wrote module registry with ${plans.length} module(s).`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
