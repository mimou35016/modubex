import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const root = process.cwd();
const outputFile = path.join(root, "src", "core", "foundation", "readiness.generated.ts");
const checkOnly = process.argv.includes("--check");

const requiredScripts = [
  "dev",
  "build",
  "start",
  "lint",
  "typecheck",
  "format",
  "test",
  "i18n:check",
  "db:migrate",
  "db:seed",
] as const;

export type ReadinessSnapshot = {
  version: string;
  requiredScripts: readonly string[];
  scriptsConfigured: number;
  lockfilePresent: boolean;
  ciPresent: boolean;
  prismaGenerated: boolean;
  milestones: readonly string[];
  currentMilestone: string;
};

function readFile(file: string): string | null {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return null;
  }
}

/** Collects the repository facts that are safe to freeze into the app bundle. */
export function collectReadinessSnapshot(repoRoot = root): ReadinessSnapshot {
  const rawPackage = readFile(path.join(repoRoot, "package.json")) ?? "{}";
  const manifest = JSON.parse(rawPackage) as {
    version?: string;
    scripts?: Record<string, string>;
  };
  const scripts = manifest.scripts ?? {};
  const scriptsConfigured = requiredScripts.filter((name) => Boolean(scripts[name])).length;

  const tasksFile = readFile(path.join(repoRoot, "docs", "tasks.md")) ?? "";
  const milestones = [...tasksFile.matchAll(/^## (M\d+)/gm)].map((match) => match[1]);
  const completedMilestones = tasksFile
    .split(/^## /m)
    .slice(1)
    .filter((section) => section.includes("Status: complete."))
    .map((section) => section.match(/^(M\d+)/)?.[1] ?? "")
    .filter(Boolean);
  const currentMilestone =
    completedMilestones[completedMilestones.length - 1] ?? milestones[0] ?? "M0";

  return {
    version: manifest.version ?? "0.0.0",
    requiredScripts: [...requiredScripts],
    scriptsConfigured,
    lockfilePresent: existsSync(path.join(repoRoot, "package-lock.json")),
    ciPresent: existsSync(path.join(repoRoot, ".github", "workflows", "ci.yml")),
    prismaGenerated: existsSync(
      path.join(repoRoot, "node_modules", ".prisma", "client", "index.d.ts"),
    ),
    milestones: milestones.length > 0 ? milestones : ["M0"],
    currentMilestone,
  };
}

function render(snapshot: ReadinessSnapshot): string {
  const lines = [
    "// Generated by scripts/generate-readiness.ts. Do not edit by hand.",
    "export type ReadinessSnapshot = {",
    "  version: string;",
    "  requiredScripts: readonly string[];",
    "  scriptsConfigured: number;",
    "  lockfilePresent: boolean;",
    "  ciPresent: boolean;",
    "  prismaGenerated: boolean;",
    "  milestones: readonly string[];",
    "  currentMilestone: string;",
    "};",
    "",
    "export const readinessSnapshot: ReadinessSnapshot = {",
    `  version: ${JSON.stringify(snapshot.version)},`,
    "  requiredScripts: [",
    ...snapshot.requiredScripts.map((name) => `    ${JSON.stringify(name)},`),
    "  ],",
    `  scriptsConfigured: ${snapshot.scriptsConfigured},`,
    `  lockfilePresent: ${snapshot.lockfilePresent},`,
    `  ciPresent: ${snapshot.ciPresent},`,
    `  prismaGenerated: ${snapshot.prismaGenerated},`,
    "  milestones: [",
    ...snapshot.milestones.map((milestone) => `    ${JSON.stringify(milestone)},`),
    "  ],",
    `  currentMilestone: ${JSON.stringify(snapshot.currentMilestone)},`,
    "};",
  ];
  return `${lines.join("\n")}\n`;
}

async function main(): Promise<void> {
  const snapshot = collectReadinessSnapshot();
  const config = await prettier.resolveConfig(outputFile);
  const content = await prettier.format(render(snapshot), {
    ...(config ?? {}),
    filepath: outputFile,
  });

  if (checkOnly) {
    const current = existsSync(outputFile) ? readFileSync(outputFile, "utf8") : "";
    if (current !== content) {
      console.error("Readiness snapshot is stale. Run `npm run readiness:generate`.");
      process.exitCode = 1;
    } else {
      console.info(
        `Readiness snapshot is up to date (${snapshot.milestones.length} milestone(s)).`,
      );
    }
    return;
  }

  writeFileSync(outputFile, content, "utf8");
  console.info(`Wrote readiness snapshot (${snapshot.milestones.length} milestone(s)).`);
}

function invokedDirectly(): boolean {
  const entry = process.argv[1];
  return Boolean(entry && path.resolve(entry) === fileURLToPath(import.meta.url));
}

if (invokedDirectly()) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
